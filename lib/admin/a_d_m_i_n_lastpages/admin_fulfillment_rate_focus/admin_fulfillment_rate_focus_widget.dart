  Future<void> _fetchStats() async {
    try {
      final appointments = await AppointmentTable().queryRows(queryFn: (q) => q);
      if (appointments.isNotEmpty) {
        final total = appointments.length;
        final completed = appointments.where((a) => a.status == 'Completed' || a.status == 'Attended').length;
        final cancelled = appointments.where((a) => a.status == 'Cancelled').length;
        final noShow = appointments.where((a) => a.status == 'No Show').length;

        _totalCount = total;
        _completedCount = completed;
        _cancelledCount = cancelled;
        _noShowCount = noShow;

        _fulfillmentRate = total > 0 ? (completed / total) * 100 : 0.0;
        final attendedOrNoShow = completed + noShow;
        _showRate = attendedOrNoShow > 0 ? (completed / attendedOrNoShow) * 100 : 0.0;
        _noShowRate = attendedOrNoShow > 0 ? (noShow / attendedOrNoShow) * 100 : 0.0;
        _cancelRate = total > 0 ? (cancelled / total) * 100 : 0.0;
      }
    } catch (e) {
      print('Error loading appointment stats: $e');
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }



